export const glyphHeight = 7;
const advance = 6;
const spaceAdvance = 4;

/** Lit cells for a line of text, in cell coordinates. */
export function pixelCells(text: string) {
  const cells: Array<[number, number]> = [];
  let x = 0;
  for (const char of text.toUpperCase()) {
    const glyph = rows[char];
    if (!glyph) { x += spaceAdvance; continue; }
    glyph.split(' ').forEach((row, y) => {
      for (let c = 0; c < row.length; c++) if (row[c] === '#') cells.push([x + c, y]);
    });
    x += advance;
  }
  return { cells, width: Math.max(0, x - 1), height: glyphHeight };
}

/** One SVG path for the text, one unit square per lit cell. */
export function pixelPath(text: string) {
  const { cells, width, height } = pixelCells(text);
  const d = cells.map(([x, y]) => `M${x} ${y}h1v1h-1z`).join('');
  return { d, width, height };
}
